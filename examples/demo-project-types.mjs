export function getProjectTypeProfile(value) {
  const normalized = String(value || "").trim().toLowerCase().replace(/[\s-]+/g, "_");
  const candidate = PROJECT_TYPE_ALIASES[normalized] || normalized || "blank";
  return PROJECT_TYPE_REGISTRY.find((profile) => profile.id === candidate)
    || PROJECT_TYPE_REGISTRY[0];
}
